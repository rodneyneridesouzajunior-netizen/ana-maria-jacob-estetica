// Explicit build step: extracts only browser-independent validation; --check verifies drift.
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=new URL('../../../painel/piloto-simples/',import.meta.url);
const target=new URL('../_shared/app-workspace-domain/',import.meta.url);
const sha=x=>createHash('sha256').update(x).digest('hex');
const copy=['operations-domain.mjs','clinic-domain.mjs','finance-domain.mjs','documents-domain.mjs','visit-workflow.mjs','facial-study-domain.mjs','patients-domain.mjs','recycle-bin.mjs'];
const transforms={
 'domain.mjs':text=>text.slice(0,text.indexOf('export function seed()')),
 'compare.mjs':text=>text.slice(0,text.indexOf('async function imageFromUrl')),
 'comparison-library.mjs':text=>text.slice(0,text.indexOf('export function comparisonRecordDraft')).replace('comparisonPhotos,comparisonSelection,resolveComparison,mountComparison','comparisonPhotos,comparisonSelection,resolveComparison').replace(/^import .*(?:feature-ui|recycle-ui)\.mjs.*\r?\n/gm,''),
 'backup.mjs':text=>text.slice(0,text.indexOf('async function verifySignatures')),
};
const check=process.argv.includes('--check'),manifest={format:1,source:'painel/piloto-simples',files:[]};
if(!check)await mkdir(target,{recursive:true});
for(const name of [...copy,...Object.keys(transforms)]){
 const original=await readFile(new URL(name,source),'utf8'),body=transforms[name]?transforms[name](original):original;
 if(!body.trim()||/\b(document|window)\./.test(body))throw Error('Extraction must not include browser code: '+name);
 const generated='// GENERATED by app-workspace/sync-domain.mjs; do not edit.\n'+body;
 manifest.files.push({name,sourceSha256:sha(original),generatedSha256:sha(generated),mode:transforms[name]?'pure-prefix':'exact-copy'});
 if(check){if(await readFile(new URL(name,target),'utf8')!==generated)throw Error('Domain drift: '+name);}else await writeFile(new URL(name,target),generated);
}
const json=JSON.stringify(manifest,null,2)+'\n';
if(check){if(await readFile(new URL('manifest.json',target),'utf8')!==json)throw Error('Domain manifest drift.');}else await writeFile(new URL('manifest.json',target),json);
console.log(check?'Domain source hashes verified.':'Pure domain bundle generated.');
